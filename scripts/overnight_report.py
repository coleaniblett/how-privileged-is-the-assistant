"""Draft of the morning report from the run's own records: docs/overnight_2026-11-03.md.

    uv run python scripts/overnight_report.py [--out docs/overnight_2026-11-03.md]

Reads results/capstone/logs/summary.json (kept across restarts), driver.log, supervisor.log and the outputs on disk. Everything it states comes
from those records; observations that need a human or an agent's reading go in the section left at the end. Safe to run while the collection is
still going (it then reports what is left). Rerun it after any restart: it does not depend on the session that produced the run.
"""

import argparse
import glob
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
os.chdir(ROOT)

LOGS = os.environ.get("OVERNIGHT_LOGS", os.path.join("results", "capstone", "logs"))


def plan():
    import importlib.util
    spec = importlib.util.spec_from_file_location("overnight_collect", os.path.join(ROOT, "scripts", "overnight_collect.py"))
    m = importlib.util.module_from_spec(spec)
    os.environ.setdefault("OVERNIGHT_LOGS", LOGS)
    spec.loader.exec_module(m)
    return m


def expected_outputs(m):
    """[(label, path)] of every output the plan should produce."""
    out = []
    for fam, stages, _ in m.PLAN:
        for st in stages:
            runs = [(m.RUN, "")] + ([(m.OFF_RUN, " (think off)")] if fam == "qwen3-8b" else [])
            for run, tag in runs:
                base = os.path.join("results", run, fam, "core")
                out.append((f"{fam} {st} scores{tag}", os.path.join(base, "scores", f"{st}.csv")))
                out.append((f"{fam} {st} authorship scores{tag}", os.path.join(base, "scores_authorship", f"{st}.csv")))
                if not tag:
                    out.append((f"{fam} {st} generation", os.path.join(base, "generations", f"{st}.jsonl")))
    return out


def fmt_s(sec):
    sec = int(sec or 0)
    return f"{sec // 3600}h{sec % 3600 // 60:02d}m" if sec >= 3600 else f"{sec // 60}m{sec % 60:02d}s"


def lines_of(path, needle):
    if not os.path.exists(path):
        return []
    return [l.rstrip() for l in open(path, encoding="utf-8", errors="replace") if needle in l]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join("docs", "overnight_2026-11-03.md"))
    args = ap.parse_args()
    m = plan()
    try:
        sm = json.load(open(os.path.join(LOGS, "summary.json"), encoding="utf-8"))
    except (OSError, ValueError):
        sm = {}
    L = ["# Overnight data collection, 2026-11-02/03", "",
         "Generated by `scripts/overnight_report.py` from `results/capstone/logs/` (`summary.json`, `driver.log`, `supervisor.log`) and the outputs on disk; "
         "see the last section for readings that need judgement. Collection only: no judge, no flags, no analysis.", ""]
    runs = sm.get("runs", [])
    first = sm.get("started") or "-"
    L += ["## What ran", "",
          f"Started {first}; finished {sm.get('finished') or 'not finished (or not recorded)'}. Driver instances: {len(runs)} "
          f"({'not recorded' if not runs else 'one uninterrupted run' if len(runs) == 1 else 'restarted ' + str(len(runs) - 1) + ' time(s); see Interruptions'}). "
          "Per task, each in its own process:", "", "| task | status | time | retries |", "|---|---|---|---|"]
    for t in sm.get("tasks", []):
        L.append(f"| {t['task']} | {t['status']} | {fmt_s(t.get('seconds'))} | {t.get('retries', 0)} |")
    if not sm.get("tasks"):
        L.append("| (no tasks recorded) | | | |")
    done_s = sum(t.get("seconds") or 0 for t in sm.get("tasks", []) if str(t.get("status", "")).startswith("ok"))
    L += ["", f"Total time in successful tasks: {fmt_s(done_s)}.", ""]

    L += ["## Interruptions and restarts", ""]
    sup = os.path.join(LOGS, "supervisor.log")
    ex = [l for l in lines_of(sup, "driver exited with code") if not l.endswith("code 0")]
    keep = sorted(glob.glob(os.path.join(LOGS, "*.interrupted-*.log")))
    L += [f"- Supervisor-recorded non-zero driver exits: {len(ex)}" + "".join(f"\n  - `{l}`" for l in ex),
          f"- Interrupted attempts whose logs were kept: {len(keep)}" + "".join(f"\n  - `{os.path.basename(p)}`" for p in keep),
          f"- Orphans swept at restart: {[n for n in sm.get('notes', []) if 'swept' in n] or 'none'}", ""]

    L += ["## Integrity checks per checkpoint", "",
          "Row counts equal texts x slots (scores) or prefills x samples (generations); no NaN/inf; render checks pass; entropy present for every scored token.", "",
          "| checkpoint | check | result | stats / issues |", "|---|---|---|---|"]
    for ck in sm.get("checkpoints", []):
        name = f"{ck['family']} {ck['stage']}"
        if ck.get("failed") and not ck.get("integrity"):
            L.append(f"| {name} | - | NOT COLLECTED | {ck.get('reason') or ck.get('errors', ['failed'])[0][:80]} |")
        for k, v in ck.get("integrity", {}).items():
            stats = ", ".join(f"{a}={b}" for a, b in v["stats"].items() if a != "anomalies")
            L.append(f"| {name} | {k} | {'OK' if v['ok'] else 'ISSUES'} | {'; '.join(v['issues']) if v['issues'] else stats} |")
    if not sm.get("checkpoints"):
        L.append("| (none yet) | | | |")
    L.append("")

    fails = [t for t in sm.get("tasks", []) if str(t.get("status", "")).startswith("failed") or t.get("retries")]
    L += ["## Failures and retries", ""] + ([f"- {t['task']}: {t['status']} (retries {t.get('retries', 0)})" for t in fails] or ["- none recorded"]) + [""]

    disk = sm.get("disk", [])
    L += ["## Disk", ""]
    if disk:
        lo = min(disk, key=lambda d: d["free_gb"])
        L += [f"- Free disk: first record {disk[0]['free_gb']} GB ({disk[0]['label']}); lowest {lo['free_gb']} GB ({lo['label']}); last {disk[-1]['free_gb']} GB ({disk[-1]['label']})."]
    L += [f"- Deleted to make room (only the Qwen weights and the regenerable datasets cache were allowed): " + ("; ".join(sm.get("notes", [])) or "see driver.log"), ""]
    L += ["```", *lines_of(os.path.join(LOGS, "driver.log"), "freed")[:6], *lines_of(os.path.join(LOGS, "driver.log"), "removed the regenerable")[:2], "```", ""]

    anomalies = []
    for ck in sm.get("checkpoints", []):
        for k, v in ck.get("integrity", {}).items():
            for a in v["stats"].get("anomalies", []):
                anomalies.append(f"{ck['family']} {ck['stage']} {k}: {a}")
    L += ["## Anomalies flagged by the checks", ""] + ([f"- {a}" for a in anomalies] or ["- none flagged"]) + [""]

    missing = [(lab, p) for lab, p in expected_outputs(m) if not os.path.exists(p)]
    L += ["## What's left to run", ""]
    if missing:
        L += [f"{len(missing)} of {len(expected_outputs(m))} expected outputs are missing; the collection is idempotent, so `bash scripts/overnight_launch.sh` "
              "(or the driver alone) runs exactly these:", ""] + [f"- {lab}" for lab, _ in missing]
    else:
        L += [f"Nothing: all {len(expected_outputs(m))} expected outputs exist."]
    L += ["", "## Readings (written by the agent or a person after looking at the data)", "", "_Not filled in by the script._", ""]
    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    open(args.out, "w", encoding="utf-8").write("\n".join(L))
    print(f"wrote {args.out} ({len(L)} lines; {len(missing)} outputs still missing)")


if __name__ == "__main__":
    main()
